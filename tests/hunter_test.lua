local ns={}
loadAddon("Modules/Hunter/Model.lua",ns)
local function model()
    assert(ns.HunterModel,"Hunter model is not implemented")
    return ns.HunterModel
end

test("positive range checks identify shooting and melee range",function()
    local m=model()
    assert(m.ResolveZone(true,true,false,nil)=="ranged")
    assert(m.ResolveZone(true,false,true,nil)=="melee")
end)

test("dead zone and far require known negative weapon checks",function()
    local m=model()
    assert(m.ResolveZone(true,false,false,true)=="deadzone")
    assert(m.ResolveZone(true,false,false,false)=="far")
    assert(m.ResolveZone(true,nil,false,false)=="unknown")
    assert(m.ResolveZone(true,false,nil,true)=="unknown")
    assert(m.ResolveZone(true,false,false,nil)=="unknown")
end)

test("no valid target is distinct from an unreadable target",function()
    local m=model()
    assert(m.ResolveZone(false,nil,nil,nil)=="none")
    assert(m.ResolveZone(nil,false,false,false)=="unknown")
end)

test("ammunition warns only below the threshold and rearms after refill",function()
    local m=model()
    local low,warn=m.AmmoTransition(false,200,200)
    assert(not low and not warn)
    low,warn=m.AmmoTransition(low,199,200)
    assert(low and warn)
    low,warn=m.AmmoTransition(low,0,200)
    assert(low and not warn)
    low,warn=m.AmmoTransition(low,400,200)
    assert(not low and not warn)
    low,warn=m.AmmoTransition(low,100,200)
    assert(low and warn)
end)

test("unknown ammunition does not rearm a warning and zero disables it",function()
    local m=model()
    local low,warn=m.AmmoTransition(true,nil,200)
    assert(low and not warn)
    low,warn=m.AmmoTransition(true,0,0)
    assert(not low and not warn)
end)

test("missing dead and unhappy pets remain distinguishable",function()
    local m=model()
    assert(m.ResolvePet(false,false,nil)=="missing")
    assert(m.ResolvePet(true,true,3)=="dead")
    assert(m.ResolvePet(true,false,1)=="unhappy")
    assert(m.ResolvePet(true,false,2)=="content")
    assert(m.ResolvePet(true,false,3)=="happy")
    assert(m.ResolvePet(true,false,nil)=="unknown")
end)
