local ns={}
loadAddon("Modules/XP/Model.lua",ns)
local function model()assert(ns.XPModel,"XP model is not implemented");return ns.XPModel end
local function sample(level,xp,maximum,at,rested,atCap)
    return {level=level,current=xp,maximum=maximum,at=at,rested=rested or 0,atCap=atCap==true}
end

test("single level rollover counts only the actual earned experience",function()
    local m=model();local s=m.New(sample(10,90,100,0),0)
    s=m.Observe(s,sample(11,10,150,60))
    local r=m.Summarize(s,60)
    assert(r.earned==20 and r.perHour==1200 and r.remaining==140 and r.eta==420)
end)

test("duplicate XP snapshots never count the same gain twice",function()
    local m=model();local s=m.New(sample(10,10,100,0),0)
    s=m.Observe(s,sample(10,30,100,60));s=m.Observe(s,sample(10,30,100,61))
    assert(m.Summarize(s,120).earned==20)
end)

test("zero time and no gains do not produce an infinite rate or ETA",function()
    local m=model();local s=m.New(sample(10,0,100,0),0)
    assert(m.Summarize(s,0).perHour==nil)
    local r=m.Summarize(s,60)
    assert(r.perHour==0 and r.eta==nil and r.percent==0)
end)

test("rested display ends at the next level boundary",function()
    local m=model();local s=m.New(sample(10,90,100,0,50),0)
    local r=m.Summarize(s,60)
    assert(r.restedEnd==100 and r.remaining==10 and r.percent==90)
end)

test("missing or unusable XP data remains explicitly unknown",function()
    local m=model();local s=m.New(sample(10,nil,100,0),0)
    local r=m.Summarize(s,60)
    assert(r.reliable==false and r.percent==nil and r.earned==nil and r.eta==nil)
end)

test("multi-level jumps rebase measurement instead of inventing level costs",function()
    local m=model();local s=m.New(sample(10,90,100,0),0)
    s=m.Observe(s,sample(12,10,200,60))
    local r=m.Summarize(s,60)
    assert(r.measurementReset==true and r.earned==0 and r.perHour==nil)
    s=m.Observe(s,sample(12,50,200,120))
    r=m.Summarize(s,120)
    assert(r.earned==40 and r.perHour==2400)
end)

test("max-level data with no XP denominator is valid and has no ETA",function()
    local m=model();local s=m.New(sample(60,0,0,0,0,true),0)
    local r=m.Summarize(s,60)
    assert(r.atCap==true and r.reliable==true and r.percent==100 and r.remaining==0 and r.eta==nil)
end)

test("reload preserves a session while a new login starts a fresh one",function()
    local m=model();local s=m.New(sample(10,10,100,0),0)
    s=m.Observe(s,sample(10,30,100,60))
    local reloaded=m.Restore(s,sample(10,30,100,120),true)
    assert(m.Summarize(reloaded,120).earned==20 and m.Summarize(reloaded,120).elapsed==120)
    local fresh=m.Restore(s,sample(10,30,100,120),false)
    assert(m.Summarize(fresh,120).earned==0 and m.Summarize(fresh,120).elapsed==0)
    assert(s.startedAt==0)
end)

test("malformed saved sessions cannot corrupt live rates",function()
    local m=model()
    local s=m.Restore({version=1,startedAt=0/0,earned=math.huge,last={}},sample(10,30,100,120),true)
    local r=m.Summarize(s,180)
    assert(r.earned==0 and r.perHour==0 and r.elapsed==60)
end)

test("XP moving backward starts a new measurement without negative gains",function()
    local m=model();local s=m.New(sample(10,90,100,0),0)
    s=m.Observe(s,sample(10,10,100,60))
    local r=m.Summarize(s,60)
    assert(r.earned==0 and r.measurementReset==true and r.eta==nil)
end)

test("regaining access to XP does not infer gains during the inaccessible interval",function()
    local m=model();local s=m.New(sample(10,10,100,0),0)
    s=m.Observe(s,sample(10,nil,100,60));s=m.Observe(s,sample(10,70,100,120))
    local r=m.Summarize(s,120)
    assert(r.earned==0 and r.measurementReset==true)
end)
